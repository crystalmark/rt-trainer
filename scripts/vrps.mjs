// Turn the NATS AIS consolidated VRP dataset into js/data/vrps.js for the aerodromes the app covers.
// Run each AIRAC cycle with the CSV from https://nats-uk.ead-it.com/cms-nats/opencms/en/Publications/digital-datasets/
//   node scripts/vrps.mjs path/to/EG_VRP_DS_AREA1_FULL_<yyyymmdd>.csv [ICAO ...]
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';

const [csvPath, ...wanted] = process.argv.slice(2);
if (!csvPath) { console.error('usage: node scripts/vrps.mjs <dataset.csv> [ICAO ...]'); process.exit(1); }
// Leeds, Leeds East (York), Manchester, Edinburgh
const ICAOS = wanted.length ? wanted : ['EGNM', 'EGCM', 'EGCC', 'EGPH'];

function parseCsv(text) {
  const rows = []; let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) { if (c === '"' && text[i + 1] === '"') { field += '"'; i++; } else if (c === '"') quoted = false; else field += c; continue; }
    if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(field); field = ''; if (row.some(Boolean)) rows.push(row); row = []; }
    else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

// '534130.00N' / '0013806.00W' -> decimal degrees
function degrees(s) {
  const m = /^(\d{2,3})(\d{2})(\d{2}(?:\.\d+)?)([NSEW])$/.exec(s.trim());
  if (!m || (m[1].length === 3) !== /[EW]/.test(m[4])) throw new Error(`Bad coordinate ${s}`);
  const v = Number(m[1]) + Number(m[2]) / 60 + Number(m[3]) / 3600;
  return Math.round((/[SW]/.test(m[4]) ? -v : v) * 1e6) / 1e6;
}

// "HARROGATE (HGT) RAILWAY STATION" -> { name: 'Harrogate Railway Station', code: 'HGT' }
function nameAndCode(official) {
  const code = (/\(([A-Z]{3})\)/.exec(official) || [])[1] || null;
  const plain = official.replace(/\s*\([A-Z]{3}\)\s*/, ' ').replace(/\s+/g, ' ').trim();
  const name = plain.toLowerCase().replace(/(^|[\s(/-])([a-z])/g, (_, p, c) => p + c.toUpperCase())
    .replace(/\b[\w()]*\d[\w()]*\b/gi, w => w.toUpperCase());
  return { name, code };
}

const [header, ...rows] = parseCsv(readFileSync(csvPath, 'utf8').replace(/^﻿/, ''));
const col = n => { const i = header.indexOf(n); if (i < 0) throw new Error(`No column "${n}" in ${csvPath}`); return i; };
const [NAME, LAT, LON, ICAO] = ['VRP name', 'Latitude', 'Longitude', 'ICAO Code'].map(col);
const out = {};
for (const icao of ICAOS) {
  out[icao] = rows.filter(r => r[ICAO] === icao)
    .map(r => ({ official: r[NAME], ...nameAndCode(r[NAME]), lat: degrees(r[LAT]), lon: degrees(r[LON]) }))
    .sort((a, b) => a.name.localeCompare(b.name));
  if (!out[icao].length) console.warn(`No VRPs for ${icao}`);
}
const dataset = basename(csvPath).replace(/\.csv$/i, '');
const date = (/(\d{4})(\d{2})(\d{2})/.exec(dataset) || []).slice(1).join('-');
const body = Object.entries(out).map(([icao, list]) => `  ${icao}: [\n${list.map(v => `    ${JSON.stringify(v)},`).join('\n')}\n  ],`).join('\n');
writeFileSync(new URL('../js/data/vrps.js', import.meta.url),
  `// UK Visual Reference Points from the NATS AIS consolidated VRP dataset (usage: unrestricted).
// Generated by scripts/vrps.mjs: regenerate each AIRAC cycle, don't edit by hand.
export const VRP_DATASET = '${dataset}';
export const VRP_EFFECTIVE = '${date}';
export const VRPS = {
${body}
};
`);
console.log(`js/data/vrps.js: ${Object.entries(out).map(([k, v]) => `${k} ${v.length}`).join(', ')} (effective ${date})`);
